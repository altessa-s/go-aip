package fieldbehavior

//go:generate optgen generate

import (
	"google.golang.org/genproto/googleapis/api/annotations"
	"google.golang.org/protobuf/proto"

	"github.com/altessa-s/go-aip/fieldinfo"
)

// DefaultStrict is the default value for [WithStrict]. When false (the
// default), Strip silently clears matching fields. When true, Strip returns a
// *BehaviorViolationError listing every populated field it would have cleared,
// leaving the message unchanged, except OUTPUT_ONLY fields, which AIP-203
// requires to be cleared without an error in every mode, and IMMUTABLE fields,
// which are compared with the stored value in every mode (see [Strip]).
const DefaultStrict = false

// DefaultFieldFormats is the default value for [WithFieldFormats]: input
// walks ([Strip], [StripCreate], [StripUpdate] and [ValidateRequired]) also
// validate the AIP-202 google.api.field_info format of every string value
// they keep, in the same pass. [StripResponse] turns it off: a response is
// server output, not input.
const DefaultFieldFormats = true

// DefaultMaxDepth is the default value for [WithMaxDepth]. Recursive protobuf schemas are supported; the limit bounds stack growth
// while traversing populated message values.
const DefaultMaxDepth = 32

// DefaultCreateBehaviors lists the behaviors stripped by [StripCreate]:
// OUTPUT_ONLY and IDENTIFIER are server-managed and must not be supplied
// by the client.
func DefaultCreateBehaviors() []annotations.FieldBehavior {
	return []annotations.FieldBehavior{
		annotations.FieldBehavior_OUTPUT_ONLY,
		annotations.FieldBehavior_IDENTIFIER,
	}
}

// DefaultUpdateBehaviors lists the behaviors handled by [StripUpdate]:
// OUTPUT_ONLY (cleared) and IMMUTABLE (compared with the stored value of
// [WithCurrent]: ignored when unchanged, a violation when changed; retained
// for the caller to compare when no stored value is supplied). IDENTIFIER is deliberately absent: per AIP-203
// the identifier addresses the resource on Update, so it must reach the
// handler.
func DefaultUpdateBehaviors() []annotations.FieldBehavior {
	return []annotations.FieldBehavior{
		annotations.FieldBehavior_OUTPUT_ONLY,
		annotations.FieldBehavior_IMMUTABLE,
	}
}

// DefaultResponseBehaviors lists the behaviors stripped by [StripResponse]:
// INPUT_ONLY fields are accepted on input but must not appear in outbound
// responses (passwords, auth tokens, …).
func DefaultResponseBehaviors() []annotations.FieldBehavior {
	return []annotations.FieldBehavior{
		annotations.FieldBehavior_INPUT_ONLY,
	}
}

// options carries fieldbehavior configuration. Tunables are generated by
// optgen — never construct this struct directly, use [WithStrict],
// [WithBehaviors], [WithMaxDepth], [WithResolver], [WithCurrent],
// [WithFieldFormats] and [WithFormatChecker].
type options struct {
	strict   bool `optgen:"default=DefaultStrict" optval:"param"`
	maxDepth int  `optgen:"default=DefaultMaxDepth"`
	// An empty behavior set disables stripping.
	behaviors []annotations.FieldBehavior `optgen:"allownull"`
	resolver  Resolver                    `optgen:"default=AnnotationResolver{}"`
	// current is the stored resource an update payload is compared with: an
	// IMMUTABLE or IDENTIFIER value that differs from it is a violation, an
	// IMMUTABLE value equal to it is retained for subsequent planning. It must be a message of the
	// payload's type ([ErrCurrentMismatch] otherwise); nil means the stored
	// value is unknown. Only update payloads have a current value.
	current proto.Message `optgen:"allownull"`
	// fieldFormats makes the walk also report every kept string value that
	// does not match the AIP-202 format of its field (google.api.field_info),
	// as a violation with Behavior FIELD_BEHAVIOR_UNSPECIFIED. Cleared fields
	// are not checked.
	fieldFormats bool `optgen:"default=DefaultFieldFormats" optval:"param"`
	// formatChecker validates the formats when [WithFieldFormats] is on: a
	// [fieldinfo.Checker] built with custom formats (an email format, say).
	// Nil uses a checker of the AIP-202 formats only.
	formatChecker *fieldinfo.Checker `optgen:"allownull"`
}

// defaultFormatChecker checks the AIP-202 formats when no [WithFormatChecker]
// is passed.
var defaultFormatChecker = fieldinfo.NewChecker()

// formats returns the checker of the walk, nil when formats are off.
func (o *options) formats() *fieldinfo.Checker {
	switch {
	case !o.fieldFormats:
		return nil
	case o.formatChecker != nil:
		return o.formatChecker
	default:
		return defaultFormatChecker
	}
}
