package unreachable

//go:generate optgen generate

import "time"

// Defaults of [NewSet] and [Run].
const (
	// DefaultMaxNames is the default maximum number of names a response
	// reports (see [WithMaxNames]). AIP-217 requires the maximum to be
	// documented on the unreachable field.
	DefaultMaxNames = 100
	// DefaultConcurrency is the default maximum number of sources [Run]
	// fetches at the same time (see [WithConcurrency]).
	DefaultConcurrency = 16
	// DefaultPartialSuccess is the default of [WithPartialSuccess]: a
	// response lists the unreachable names instead of failing, the AIP-217
	// behavior of an API without a return_partial_success field.
	DefaultPartialSuccess = true
)

// options configures a [Set] and [Run]. Tunables are generated by optgen.
type options struct {
	// WithMaxNames bounds the names a response reports, independently of the
	// page size. Over the limit the names are first up-scoped with
	// [WithUpscope], then truncated to the lexicographically first ones. Zero
	// is unlimited; a negative value keeps the default.
	maxNames int `optgen:"default=DefaultMaxNames" optval:"positive=allow_zero"`
	// WithUpscope maps a name to the name of its broader scope (a zone to its
	// region, a resource to its location). It is applied only when the names
	// exceed [WithMaxNames]; a result that is not a valid service-relative
	// name keeps the original name. Nil disables up-scoping.
	upscope func(name string) string `optgen:"allownull"`
	// WithConcurrency bounds the sources [Run] fetches at the same time. Zero
	// is unlimited; a negative value keeps the default.
	concurrency int `optgen:"default=DefaultConcurrency" optval:"positive=allow_zero"`
	// WithSourceTimeout bounds each fetch of [Run]; a source that exceeds it
	// is unreachable. Zero or a negative value sets no timeout of its own.
	sourceTimeout time.Duration
	// WithPartialSuccess is the request's return_partial_success: false makes
	// [Run] fail with an *[Error] as soon as a source is unreachable.
	partialSuccess bool `optgen:"default=DefaultPartialSuccess" optval:"param"`
	// WithClassifier decides which fetch errors make a source unreachable;
	// any other error fails [Run]. Nil uses [IsUnreachable].
	classifier func(err error) bool `optgen:"default=IsUnreachable"`
}

// isUnreachable applies the classifier, [IsUnreachable] when it is nil.
func (o *options) isUnreachable(err error) bool {
	if o.classifier == nil {
		return IsUnreachable(err)
	}

	return o.classifier(err)
}
